                CREATE FUNCTION cmdb_ensure_partition(parent text, part text, key text, low timestamptz, high timestamptz)
                RETURNS boolean LANGUAGE plpgsql AS $$
                BEGIN
                    IF to_regclass(part) IS NOT NULL THEN
                        RETURN false;
                    END IF;
                    -- Nothing may land in the default partition between moving its rows and attaching the new one. The lock also
                    -- makes two callers take turns; the second finds the partition made.
                    EXECUTE format('LOCK TABLE %I IN EXCLUSIVE MODE', parent || '_default');
                    IF to_regclass(part) IS NOT NULL THEN
                        RETURN false;
                    END IF;
                    EXECUTE format('CREATE TABLE %I (LIKE %I INCLUDING DEFAULTS)', part, parent);
                    EXECUTE format('WITH moved AS (DELETE FROM %I WHERE %I >= $1 AND %I < $2 RETURNING *) INSERT INTO %I SELECT * FROM moved',
                                   parent || '_default', key, key, part) USING low, high;
                    EXECUTE format('ALTER TABLE %I ATTACH PARTITION %I FOR VALUES FROM (%L) TO (%L)', parent, part, low, high);
                    RETURN true;
                END $$;
